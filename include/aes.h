/* -- GF(2^8) multiply (constexpr for table generation) -- */
constexpr uint8_t xtime(uint8_t a) {
    return static_cast<uint8_t>((a << 1) ^ ((a >> 7) * 0x1b));
}

constexpr uint8_t gmul(uint8_t a, uint8_t b) {
    uint8_t p = 0;
    for (int i = 0; i < 8; ++i) {
        if (b & 1) p ^= a;
        a = xtime(a);
        b >>= 1;
    }
    return p;
}

/* -- T-table generation (compile-time) -- */
constexpr uint32_t make_te0(uint8_t s) {
    uint8_t s2 = xtime(s);
    uint8_t s3 = static_cast<uint8_t>(s2 ^ s);
    return (static_cast<uint32_t>(s2) << 24) | (static_cast<uint32_t>(s) << 16) |
           (static_cast<uint32_t>(s) << 8)   | static_cast<uint32_t>(s3);
}

constexpr uint32_t make_td0(uint8_t s) {
    uint8_t se = gmul(s, 0x0e);
    uint8_t s9 = gmul(s, 0x09);
    uint8_t sd = gmul(s, 0x0d);
    uint8_t sb = gmul(s, 0x0b);
    return (static_cast<uint32_t>(se) << 24) | (static_cast<uint32_t>(s9) << 16) |
           (static_cast<uint32_t>(sd) << 8)  | static_cast<uint32_t>(sb);
}

constexpr uint32_t rotr32(uint32_t v, int n) {
    return (v >> n) | (v << (32 - n));
}

