/* -- Big-endian load/store (safe, no UB) -- */
inline uint32_t load_be32(const uint8_t* p) {
    uint32_t v;
    std::memcpy(&v, p, 4);
    // Convert from big-endian
    return (static_cast<uint32_t>(p[0]) << 24) |
           (static_cast<uint32_t>(p[1]) << 16) |
           (static_cast<uint32_t>(p[2]) << 8)  |
           static_cast<uint32_t>(p[3]);
}

inline void store_be32(uint8_t* p, uint32_t v) {
    p[0] = static_cast<uint8_t>(v >> 24);
    p[1] = static_cast<uint8_t>(v >> 16);
    p[2] = static_cast<uint8_t>(v >> 8);
    p[3] = static_cast<uint8_t>(v);
}

/* -- XOR helpers (64-bit word, safe via memcpy) -- */
inline void xor_block(uint8_t* dst, const uint8_t* a, const uint8_t* b, size_t len) {
    // Process 8 bytes at a time using uint64_t via memcpy (no aliasing violation)
    size_t i = 0;
    for (; i + 8 <= len; i += 8) {
        uint64_t va, vb;
        std::memcpy(&va, a + i, 8);
        std::memcpy(&vb, b + i, 8);
        va ^= vb;
        std::memcpy(dst + i, &va, 8);
    }
    for (; i < len; ++i) {
        dst[i] = a[i] ^ b[i];
    }
}

inline void xor_block_inplace(uint8_t* dst, const uint8_t* src, size_t len) {
    size_t i = 0;
    for (; i + 8 <= len; i += 8) {
        uint64_t vd, vs;
        std::memcpy(&vd, dst + i, 8);
        std::memcpy(&vs, src + i, 8);
        vd ^= vs;
        std::memcpy(dst + i, &vd, 8);
    }
    for (; i < len; ++i) {
        dst[i] ^= src[i];
    }
}

/* Constant-time comparison for tags */
inline bool constant_time_eq(const uint8_t* a, const uint8_t* b, size_t len) {
    volatile uint8_t diff = 0;
    for (size_t i = 0; i < len; ++i) {
        diff |= a[i] ^ b[i];
    }
    return diff == 0;
}

